# Claude Code TUI - Automated Install (PowerShell)
# Usage: run .\install.ps1 in project directory
# Self-contained portable Node.js, does NOT depend on system Node.js version

$ErrorActionPreference = 'Stop'
Write-Host '=== Claude Code TUI Install ===' -ForegroundColor Green

$projectRoot = (Get-Location).Path
$nodeDir = "$projectRoot\runtime\node"
$nodeExe = "$nodeDir\node.exe"
$npmCmd = "$nodeDir\npm.cmd"

# Portable Node.js version (LTS)
$nodeVersion = '22.14.0'
$nodeZip = "node-v$nodeVersion-win-x64.zip"
$nodeUrl = "https://nodejs.org/dist/v$nodeVersion/$nodeZip"

# 0. Ensure usable Node.js
Write-Host "`n[0/3] Checking Node.js runtime..." -ForegroundColor Yellow

if (-not (Test-Path $nodeExe)) {
    # Check system Node.js first
    $sysNode = Get-Command node -ErrorAction SilentlyContinue
    $useSystemNode = $false
    if ($sysNode) {
        $sysVer = (node -v 2>$null) -replace '^v', ''
        if ($sysVer) {
            $sysMajor = [int]($sysVer.Split('.')[0])
            if ($sysMajor -ge 16) {
                Write-Host "  System Node.js v$sysVer OK, no need to download" -ForegroundColor Green
                $nodeExe = 'node'
                $npmCmd = 'npm'
                $useSystemNode = $true
            }
        }
    }

    if (-not $useSystemNode) {
        Write-Host "  System Node.js too old or missing, downloading portable Node.js v$nodeVersion..." -ForegroundColor Yellow
        Write-Host '    (about 30MB, first install only)' -ForegroundColor Gray

        $zipPath = "$env:TEMP\$nodeZip"
        try {
            Invoke-WebRequest -Uri $nodeUrl -OutFile $zipPath -ErrorAction Stop
        } catch {
            throw "Download failed. Manually download $nodeUrl and extract to $nodeDir `n  or install Node.js 16+: https://nodejs.org"
        }

        Write-Host '  Extracting...' -ForegroundColor Yellow
        $extractDir = "$env:TEMP\node-extract"
        if (Test-Path $extractDir) { Remove-Item -Recurse -Force $extractDir }
        Expand-Archive -Path $zipPath -DestinationPath $extractDir -Force
        Remove-Item $zipPath

        # Move extracted folder to runtime\node
        $extractedFolder = Get-ChildItem -Path $extractDir -Directory | Select-Object -First 1
        if (Test-Path $nodeDir) { Remove-Item -Recurse -Force $nodeDir }
        $parentDir = Split-Path $nodeDir -Parent
        if (-not (Test-Path $parentDir)) { New-Item -ItemType Directory -Path $parentDir -Force | Out-Null }
        Move-Item -Path $extractedFolder.FullName -Destination $nodeDir
        Remove-Item -Recurse -Force $extractDir

        Write-Host '  Portable Node.js ready' -ForegroundColor Green
    }
} else {
    Write-Host '  Portable Node.js already exists' -ForegroundColor Green
}

# 1. Install dependencies and build
Write-Host "`n[1/3] Installing dependencies + building..." -ForegroundColor Yellow
if ($useSystemNode) {
    & npm install
    if ($LASTEXITCODE -ne 0) { throw 'npm install failed' }
    & npm run build
    if ($LASTEXITCODE -ne 0) { throw 'build failed' }
} else {
    & $npmCmd install --scripts-prepend-node-path
    if ($LASTEXITCODE -ne 0) { throw 'npm install failed' }
    & $npmCmd run build --scripts-prepend-node-path
    if ($LASTEXITCODE -ne 0) { throw 'build failed' }
}

# 2. Set environment variable
Write-Host "`n[2/3] Configuring..." -ForegroundColor Yellow
[Environment]::SetEnvironmentVariable('CLAUDE_TUI_HOME', $projectRoot, 'User')
Write-Host "  CLAUDE_TUI_HOME = $projectRoot" -ForegroundColor Green

# 3. Find claude.exe / claude.cmd path
$claudeExe = (Get-Command claude -ErrorAction SilentlyContinue).Source
if (-not $claudeExe) { $claudeExe = "$env:APPDATA\npm\claude.cmd" }
if (-not (Test-Path $claudeExe)) { $claudeExe = "$env:USERPROFILE\.local\bin\claude.exe" }
if (-not (Test-Path $claudeExe)) { $claudeExe = "$env:LOCALAPPDATA\bin\claude.exe" }
if (-not (Test-Path $claudeExe)) { $claudeExe = 'claude' }

$profilePath = $PROFILE
if (-not $profilePath) {
    $profilePath = "$env:USERPROFILE\Documents\WindowsPowerShell\Microsoft.PowerShell_profile.ps1"
}
$profileDir = Split-Path $profilePath -Parent
if (-not (Test-Path $profileDir)) { New-Item -ItemType Directory -Path $profileDir -Force | Out-Null }

# Build claude function (avoids here-string nesting issues)
$newFunc = @()
$newFunc += '# Claude Code TUI - type claude to open history manager'
$newFunc += '# Auto-generated by install.ps1, falls back to original Claude if TUI fails'
$newFunc += 'function claude {'
$newFunc += '    $tuiHome = [Environment]::GetEnvironmentVariable(''CLAUDE_TUI_HOME'', ''User'')'
$newFunc += '    if ($args.Count -gt 0) {'
$newFunc += "        & '$claudeExe' `$args"
$newFunc += '    } elseif ($tuiHome -and (Test-Path "$tuiHome\dist\main.js")) {'
$newFunc += '        # Use portable Node.js if present, otherwise system node'
$newFunc += '        $node = if (Test-Path "$tuiHome\runtime\node\node.exe") { "$tuiHome\runtime\node\node.exe" } else { ''node'' }'
$newFunc += '        & $node "$tuiHome\dist\main.js"'
$newFunc += '        if ($LASTEXITCODE -ne 0) {'
$newFunc += '            Write-Host ''TUI failed, falling back to original Claude...'' -ForegroundColor Yellow'
$newFunc += "            & '$claudeExe'"
$newFunc += '        }'
$newFunc += '    } else {'
$newFunc += "        & '$claudeExe'"
$newFunc += '    }'
$newFunc += '}'
$newFunc = $newFunc -join "`n"

# Read current Profile
$oldContent = ''
if (Test-Path $profilePath) {
    $oldContent = (Get-Content $profilePath -Raw) -replace "`r`n", "`n"
}
# Remove previously generated claude function block
$pattern = '(?ms)(^`r?`n)?# Claude Code TUI.*?^function claude\s*\{.*?^\}`r?`n?'
$newContent = $oldContent -replace $pattern, ''
$newContent = $newContent.TrimEnd()

# Append new function
if ($newContent.Length -gt 0) {
    $newContent = $newContent + "`n`n" + $newFunc.TrimStart()
} else {
    $newContent = $newFunc.TrimStart()
}

Set-Content -Path $profilePath -Value $newContent
Write-Host '  Profile updated' -ForegroundColor Green

Write-Host "`nInstall complete! Restart PowerShell and type claude to launch." -ForegroundColor Green
Write-Host 'If you move the project, re-run .\install.ps1 in the new location.' -ForegroundColor Yellow
